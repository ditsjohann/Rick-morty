"""Hand-drawn 16x16 item sprites (ASCII art). '.' = transparent."""
from paint import hexc

S = {}
P = {}


def sprite(name, palette, rows):
    rows = [r for r in rows.strip('\n').split('\n')]
    assert len(rows) == 16, (name, len(rows))
    for r in rows:
        assert len(r) == 16, (name, r, len(r))
    S[name] = rows
    P[name] = {k: (hexc(v) if isinstance(v, str) else v) for k, v in palette.items()}


