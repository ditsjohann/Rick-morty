def camel(name):
    parts = name.split('_')
    return parts[0] + ''.join(p.capitalize() for p in parts[1:])


class Cube:
    def __init__(self, uv, box, mat=None, decals=None, face_mats=None, dilation=0.0, mirror=False, paint=True):
        self.uv, self.box, self.mat, self.decals = uv, box, mat, decals
        self.face_mats, self.dilation, self.mirror, self.paint = face_mats, dilation, mirror, paint


class Part:
    def __init__(self, name, parent, pivot=(0, 0, 0), rot=(0, 0, 0), cubes=(), field=True):
        self.name, self.parent, self.pivot, self.rot, self.cubes, self.field = name, parent, pivot, rot, list(cubes), field


def fmt(v):
    s = ('%.4f' % v).rstrip('0').rstrip('.')
    if s in ('-0', ''):
        s = '0'
    return s + 'F'


def emit_java(m):
    cls = m['cls']
    entity = m['entity']
    lines = []
    lines.append('package com.ditsjohann.mayhem.client.model;')
    lines.append('')
    lines.append('import com.ditsjohann.mayhem.MultiverseMayhem;')
    lines.append('import com.ditsjohann.mayhem.entity.mob.%s;' % entity)
    lines.append('import net.minecraft.client.model.*;')
    lines.append('import net.minecraft.client.render.RenderLayer;')
    lines.append('import net.minecraft.client.render.entity.model.EntityModelLayer;')
    lines.append('import net.minecraft.client.render.entity.model.SinglePartEntityModel;')
    lines.append('import net.minecraft.util.math.MathHelper;')
    lines.append('')
    lines.append('/** GENERATED by tools/gen_models.py — edit the spec there, not this file. */')
    lines.append('public class %s extends SinglePartEntityModel<%s> {' % (cls, entity))
    lines.append('    public static final EntityModelLayer LAYER = new EntityModelLayer(MultiverseMayhem.id("%s"), "main");' % m['id'])
    lines.append('    private final ModelPart root;')
    for p in m['parts']:
        if p.field:
            lines.append('    private final ModelPart %s;' % camel(p.name))
    lines.append('')
    lines.append('    public %s(ModelPart root) {' % cls)
    lines.append('        super(%s);' % m.get('layer', 'RenderLayer::getEntityCutoutNoCull'))
    lines.append('        this.root = root;')
    for p in m['parts']:
        if p.field:
            parent = 'root' if p.parent == 'root' else 'this.' + camel(p.parent)
            lines.append('        this.%s = %s.getChild("%s");' % (camel(p.name), parent, p.name))
    lines.append('    }')
    lines.append('')
    lines.append('    public static TexturedModelData getTexturedModelData() {')
    lines.append('        ModelData data = new ModelData();')
    lines.append('        ModelPartData root = data.getRoot();')
    for p in m['parts']:
        b = 'ModelPartBuilder.create()'
        for c in p.cubes:
            if c.mirror:
                b += '.mirrored()'
            b += '.uv(%d, %d)' % c.uv
            x, y, z, w, h, d = c.box
            if c.dilation:
                b += '.cuboid(%s, %s, %s, %s, %s, %s, new Dilation(%s))' % (fmt(x), fmt(y), fmt(z), fmt(w), fmt(h), fmt(d), fmt(c.dilation))
            else:
                b += '.cuboid(%s, %s, %s, %s, %s, %s)' % (fmt(x), fmt(y), fmt(z), fmt(w), fmt(h), fmt(d))
            if c.mirror:
                b += '.mirrored(false)'
        px, py, pz = p.pivot
        rx, ry, rz = p.rot
        parent = 'root' if p.parent == 'root' else camel(p.parent) + 'D'
        lines.append('        ModelPartData %sD = %s.addChild("%s", %s, ModelTransform.of(%s, %s, %s, %s, %s, %s));' % (
            camel(p.name), parent, p.name, b, fmt(px), fmt(py), fmt(pz), fmt(rx), fmt(ry), fmt(rz)))
    lines.append('        return TexturedModelData.of(data, %d, %d);' % m['size'])
    lines.append('    }')
    lines.append('')
    lines.append('    @Override')
    lines.append('    public ModelPart getPart() {')
    lines.append('        return root;')
    lines.append('    }')
    lines.append('')
    lines.append('    @Override')
    lines.append('    public void setAngles(%s entity, float limbAngle, float limbDistance, float animationProgress, float headYaw, float headPitch) {' % entity)
    lines.append('        getPart().traverse().forEach(ModelPart::resetTransform);')
    for l in m['anim'].strip('\n').split('\n'):
        lines.append('        ' + l.strip() if l.strip() else '')
    lines.append('    }')
    lines.append('}')
    os.makedirs(JAVA_DIR, exist_ok=True)
    with open(os.path.join(JAVA_DIR, cls + '.java'), 'w') as f:
        f.write('\n'.join(lines) + '\n')


def paint_model(m, tex_name, override=None, seed=7, glow=True):
    w, h = m['size']
    cv = Canvas(w, h, seed)
    override = override or {}
    for p in m['parts']:
        for i, c in enumerate(p.cubes):
            if not c.paint:
                continue
            key = '%s.%d' % (p.name, i)
            mat = override.get(key, override.get(p.name, c.mat))
            decals = override.get(key + '.decals', override.get(p.name + '.decals', c.decals))
            face_mats = override.get(key + '.faces', c.face_mats)
            x, y, z, bw, bh, bd = c.box
            paint_cuboid(cv, c.uv, (int(bw), int(bh), int(bd)), mat, decals, face_mats)
    os.makedirs(TEX_DIR, exist_ok=True)
    cv.save(os.path.join(TEX_DIR, tex_name + '.png'), os.path.join(TEX_DIR, tex_name + '_glow.png') if glow else None)
    return cv


def check_uv_overlap(m):
    occupied = {}
    for p in m['parts']:
        for i, c in enumerate(p.cubes):
            u, v = c.uv
            bw, bh, bd = int(c.box[3]), int(c.box[4]), int(c.box[5])
            for name, (x, y, fw, fh) in faces(u, v, bw, bh, bd).items():
                for yy in range(y, y + fh):
                    for xx in range(x, x + fw):
                        if xx >= m['size'][0] or yy >= m['size'][1]:
                            raise SystemExit('UV out of bounds in %s: %s cube %d' % (m['cls'], p.name, i))
                        owner = occupied.get((xx, yy))
                        tag = (u, v, bw, bh, bd)
                        if owner and owner != tag:
                            raise SystemExit('UV overlap in %s at %d,%d: %s vs %s' % (m['cls'], xx, yy, owner, tag))
                        occupied[(xx, yy)] = tag


