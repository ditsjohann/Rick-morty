def agent_texture():
    cv = Canvas(64, 64, 99)
    skin = Material(hexc('9FB3C8'), noise=0.08, border=0.1)
    suit = Material(hexc('2C3140'), noise=0.06, border=0.18, grad=0.1)
    shoe = hexc('121318')
    visor = hexc('F2C230')
    head_decals = {'front': [rect_decal(0, 3, 8, 2, hexc('15161C')), rect_decal(1, 3, 6, 1, visor, glow=visor), rect_decal(2, 6, 4, 1, hexc('5E7088'))]}
    paint_cuboid(cv, (0, 0), (8, 8, 8), skin, head_decals)
    # hat layer: flat cap with band
    hatm = Material(hexc('1D2130'), noise=0.05, border=0.1)
    for name, (x, y, fw, fh) in faces(32, 0, 8, 8, 8).items():
        if name in ('top',):
            hatm.fill(cv, x, y, fw, fh, name)
        elif name != 'bottom':
            for yy in range(2):
                for xx in range(fw):
                    cv.put(x + xx, y + yy, shade(hexc('1D2130'), -0.1 if yy else 0.05))
            for xx in range(fw):
                cv.put(x + xx, y + 2, visor if name == 'front' and 2 <= xx <= 5 else hexc('C9A020'))
    body_decals = {'front': [rect_decal(3, 0, 2, 5, hexc('E8ECF2')), rect_decal(3, 1, 2, 6, hexc('F2C230')), rect_decal(3, 0, 2, 1, hexc('E8ECF2')),
                             pixel_decal([(1, 3)], hexc('FFE070'), glow=hexc('FFE070')), rect_decal(0, 9, 8, 1, hexc('121318'))]}
    paint_cuboid(cv, (16, 16), (8, 12, 4), suit, body_decals)
    arm_decals = {k: rect_decal(0, -3, 4 if k in ('front', 'back') else 4, 3, hexc('9FB3C8')) for k in ('front', 'back', 'west', 'east')}
    arm_decals['bottom'] = rect_decal(0, 0, 4, 4, hexc('9FB3C8'))
    paint_cuboid(cv, (40, 16), (4, 12, 4), suit, arm_decals)
    leg_decals = {k: rect_decal(0, -2, 4, 2, shoe) for k in ('front', 'back', 'west', 'east')}
    leg_decals['bottom'] = rect_decal(0, 0, 4, 4, shoe)
    paint_cuboid(cv, (0, 16), (4, 12, 4), suit, leg_decals)
    os.makedirs(TEX_DIR, exist_ok=True)
    cv.save(os.path.join(TEX_DIR, 'customs_agent.png'), os.path.join(TEX_DIR, 'customs_agent_glow.png'))


